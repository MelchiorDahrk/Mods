-- Run the same filtering contract against both engine adapters. Setting changes
-- must apply without entering another cell or advancing the simulation.
return function(enter, set, expect)
    set('density', 32)
    set('whitelist', '')
    set('blacklist', '')
    enter("Uvirith's Grave", true, false)
    set('whitelist', " ; UVIRITH'S GRAVE ; Balmora, Guild of Mages; Test [1].*% Cell;\r\n Another Interior \n ; ")
    expect(true, 'whitelist did not apply while paused')
    enter('Balmora, Guild of Mages', true, true)
    enter('Test [1].*% Cell', true, true)
    enter('Another Interior', true, true)
    enter('Balmora', true, false) -- Commas belong to cell names.
    enter('Guild of Mages', true, false)
    enter('Another Interior Annex', true, false) -- Exact names, no substrings.
    enter('Test 1xx Cell', true, false) -- Entries are not Lua patterns.
    enter('Andrano Ancestral Tomb', true, true) -- Automatic rules still apply.
    set('blacklist', ' ; ANDRANO ANCESTRAL TOMB ; Another Interior\r\nBalmora, Guild of Mages ; ')
    expect(false, 'blacklist did not apply while paused')
    enter('Another Interior', true, false)
    enter('Balmora, Guild of Mages', true, false)
    set('whitelist', 'Andrano Ancestral Tomb; Balmora, Guild of Mages')
    expect(false, 'whitelist overrode blacklist')
    enter('Andrano Ancestral Tomb', true, false)
    enter('Samarys Ancestral Tomb', true, true) -- Only the named tomb is blocked.
    enter('Andrano Ancestral Tomb', true, false)
    set('blacklist', '')
    expect(true, 'clearing blacklist did not restore automatic match')
    enter('Balmora, Guild of Mages', true, true)
    set('whitelist', '')
    expect(false, 'clearing whitelist did not restore automatic rules')
    set('whitelist', 'Balmora, Guild of Mages; Tomb outside')
    expect(true)
    set('density', 0)
    expect(false, 'whitelist bypassed zero density')
    set('blacklist', 'Balmora, Guild of Mages')
    set('density', 32)
    expect(false, 'density change bypassed blacklist')
    set('blacklist', '')
    expect(true)
    enter('Balmora, Guild of Mages', false, false)
    enter('Tomb outside', false, false)
    -- Empty entries and malformed stored values must never match or crash.
    set('whitelist', ' ; \t;\r\n ')
    set('blacklist', ' ; \t;\r\n ')
    enter('', true, false)
    enter('Ordinary Interior', true, false)
    enter('Andrano Ancestral Tomb', true, true)
    set('blacklist', false)
    expect(true)
    set('whitelist', {})
    enter('Ordinary Interior', true, false)
    set('whitelist', '')
    set('blacklist', '')
    -- Cell browsers store sets, which also support names containing semicolons.
    enter('Mod Interior; with punctuation', true, false)
    set('whitelist', { ['MOD INTERIOR; WITH PUNCTUATION'] = true, ['Ordinary Interior'] = false })
    expect(true, 'table whitelist did not apply while paused')
    set('blacklist', { ['Mod Interior; with punctuation'] = true })
    expect(false, 'table blacklist did not override whitelist')
    set('blacklist', {})
    expect(true, 'clearing table blacklist did not restore whitelist')
    set('whitelist', {})
    expect(false, 'clearing table whitelist did not apply')
end
